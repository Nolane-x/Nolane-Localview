const fallback = messages.en;

export function isSupportedLocale(value: string): value is SupportedLocale {
  return (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function normalizeLocale(value: unknown): SupportedLocale {
  if (typeof value !== 'string') return DEFAULT_LOCALE;
  if (isSupportedLocale(value)) return value;
  const lower = value.toLowerCase();
  if (lower.startsWith('zh-hant') || lower === 'zh-tw' || lower === 'zh-hk') return 'zh-TW';
  if (lower.startsWith('zh')) return 'zh-CN';
  if (lower.startsWith('pt')) return 'pt-BR';
  const base = lower.split('-')[0];
  const matched = SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === base);
  return matched ?? DEFAULT_LOCALE;
}

export function translate(locale: SupportedLocale, key: MessageKey): string {
  return messages[locale][key] ?? fallback[key] ?? key;
}

export function applyDocumentLocale(locale: SupportedLocale): void {
  document.documentElement.lang = locale;
  document.documentElement.dir = 'ltr';
}

export function formatLocalTime(locale: SupportedLocale, value: string): string {
  try {
    return new Intl.DateTimeFormat(locale, {
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
    }).format(new Date(value));
  } catch {
    return '—';
  }
}
